function normalize(text: string): string {
  return text.toLowerCase().normalize("NFKD").replace(/[̀-ͯ]/g, "").trim();
}

// The word itself plus the English words it stands for. A Spanish word matches by prefix in both
// directions, so "comi" finds "comida" and the plural "mascotas" finds "mascota".
export function englishAlternatives(word: string): string[] {
  const needle = normalize(word);
  const out = new Set<string>([needle]);
  if (needle.length >= 3) {
    for (const [spanish, english] of Object.entries(DICTIONARY)) {
      if (spanish.startsWith(needle) || needle.startsWith(spanish)) english.forEach((term) => out.add(term));
    }
  }
  return [...out];
}
