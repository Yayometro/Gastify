// Regenerates src/components/icons/legacyIconRegistry.ts: an explicit list of the
// react-icons the app really uses, so the bundler ships only those instead of the
// whole md/fa/ai/gi packs (`import * as` pulled ~8 MB of icons into every page).
//
// Names come from: every "xx/Name" and bare "XxName" string literal in src, the
// picker list (defaultIconsDB.ts) and the names stored in the database
// (scripts/data/stored-icon-names.json). Run after adding an icon name:
//   node scripts/generate-icon-registry.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const COLLECTIONS = ["md", "fa", "ai", "gi"];
const names = new Set();

function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (/\.(ts|tsx)$/.test(entry.name) && !/\.test\./.test(entry.name) && !full.endsWith("legacyIconRegistry.ts")) scan(fs.readFileSync(full, "utf8"));
  }
}

function scan(raw) {
  // Comments (examples, commented-out entries) are not usage.
  const text = raw.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
  for (const m of text.matchAll(/["'`](md|fa|ai|gi)\/([A-Z][A-Za-z0-9]+)["'`]/g)) names.add(`${m[1]}/${m[2]}`);
  for (const m of text.matchAll(/["'`]((Md|Fa|Ai|Gi)[A-Z][A-Za-z0-9]+)["'`]/g)) names.add(`${m[2].toLowerCase()}/${m[1]}`);
}

walk(path.join(root, "src"));
for (const stored of JSON.parse(fs.readFileSync(path.join(root, "scripts/data/stored-icon-names.json"), "utf8"))) names.add(stored);

const packs = Object.fromEntries(COLLECTIONS.map((c) => [c, require(`react-icons/${c}`)]));
const missing = [...names].filter((n) => !packs[n.split("/")[0]]?.[n.split("/")[1]]);
if (missing.length) {
  console.error("These names do not exist in react-icons (typo?):", missing);
  process.exit(1);
}

const byCollection = Object.fromEntries(COLLECTIONS.map((c) => [c, [...names].filter((n) => n.startsWith(c + "/")).map((n) => n.split("/")[1]).sort()]));
let out = `// GENERATED by scripts/generate-icon-registry.mjs - do not edit by hand.\n// Only the react-icons the app uses (${names.size}); see the script for how the list is built.\nimport type { IconType } from "react-icons";\n`;
for (const c of COLLECTIONS) if (byCollection[c].length) out += `import { ${byCollection[c].join(", ")} } from "react-icons/${c}";\n`;
out += `\nexport const LEGACY_ICONS: Record<string, IconType> = {\n`;
for (const c of COLLECTIONS) for (const n of byCollection[c]) out += `  "${c}/${n}": ${n},\n`;
out += `};\n`;
fs.writeFileSync(path.join(root, "src/components/icons/legacyIconRegistry.ts"), out);
console.log(`registry: ${names.size} icons`, Object.fromEntries(COLLECTIONS.map((c) => [c, byCollection[c].length])));
